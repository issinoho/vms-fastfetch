#!/usr/bin/env python3
"""gen_mms.py - generate vms/sources.mms (object list and per-object MMS rules).

Every .c under src/ (except src/3rdparty until the config phase needs
yyjson) becomes $(OBJ)<basename>.OBJ, so basenames must be unique.  Every
object depends on every header: the program is small and this keeps MMS
correct without dependency scanning.  Run after adding or removing source
files or changing vms/config/ccflags.txt; the output is committed.
"""
import pathlib
import sys

top = pathlib.Path(__file__).resolve().parent.parent
# cpuid_x86.c: compiled
# with clang by BUILD.COM on x86-64 only (D11), linked via ARCH_OBJS.
EXCLUDE = ("src/vms/cpuid_x86.c",)


def vms_path(rel):
    """src/common/strbuf.c -> [.src.common]strbuf.c"""
    parts = rel.split("/")
    return "[." + ".".join(parts[:-1]) + "]" + parts[-1]


def mms_list(name, items):
    if not items:
        return [f"{name} ="]
    out = [f"{name} = {items[0]}" + (", -" if len(items) > 1 else "")]
    for i, it in enumerate(items[1:], 1):
        out.append(f"\t{it}" + (", -" if i < len(items) - 1 else ""))
    return out


def main():
    srcs = sorted(p.relative_to(top).as_posix() for p in (top / "src").rglob("*.c"))
    srcs = [s for s in srcs if not s.startswith(EXCLUDE)]
    hdrs = sorted(p.relative_to(top).as_posix() for p in (top / "src").rglob("*.h"))
    hdrs = [h for h in hdrs if not h.startswith(EXCLUDE)]
    bases = [pathlib.PurePosixPath(s).stem for s in srcs]
    dup = {b for b in bases if bases.count(b) > 1}
    if dup:
        sys.exit(f"gen_mms: duplicate source basenames: {sorted(dup)}")
    ccqual = (top / "vms" / "config" / "ccflags.txt").read_text().strip()

    lines = ["! Generated by tools/gen_mms.py - do not edit", "",
             f"CC_QUAL = {ccqual}", ""]
    lines += mms_list("OBJS", [f"$(OBJ){b}.OBJ" for b in bases]) + [""]
    lines += mms_list("HDRS", [vms_path(h) for h in hdrs]) + [""]
    for s, b in zip(srcs, bases):
        lines.append(f"$(OBJ){b}.OBJ : {vms_path(s)} $(HDRS)")
        lines.append(f"\t$(CC) $(CFLAGS)/OBJECT=$(MMS$TARGET) {vms_path(s)}")
        lines.append("")
    (top / "vms" / "sources.mms").write_text("\n".join(lines))
    print(f"gen_mms: {len(srcs)} sources, {len(hdrs)} headers -> vms/sources.mms")


main()
