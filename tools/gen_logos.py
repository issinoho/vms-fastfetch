#!/usr/bin/env python3
"""gen_logos.py - generate src/logo/logo_builtin.c from src/logo/logos.def.

Replaces upstream fastfetch's CMake step that turns logo .txt files into C
strings.  Run after changing anything under src/logo/; the output is
committed so the VMS build needs no Python.
"""
import pathlib
import sys

top = pathlib.Path(__file__).resolve().parent.parent
logo_dir = top / "src" / "logo"


def c_string(text):
    out = []
    for line in text.split("\n"):
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        if any(ord(c) > 126 or ord(c) < 32 for c in esc):
            sys.exit(f"gen_logos: non-ASCII character in logo line: {line!r}")
        out.append(f'    "{esc}\\n"')
    # The last line has no newline.
    out[-1] = out[-1][:-3] + '"'
    return "\n".join(out)


def main():
    entries = []
    for raw in (logo_dir / "logos.def").read_text().splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        f, names, colors, key, title = [x.strip() for x in raw.split("|")]
        names = [n.strip() for n in names.split(",")]
        colors = [c.strip() for c in colors.split(",") if c.strip()]
        if len(names) > 3 or len(colors) > 9:
            sys.exit(f"gen_logos: too many names or colours for {f}")
        text = (logo_dir / "ascii" / f).read_text().rstrip("\n")
        entries.append((f, names, colors, key, title, text))

    lines = [
        "/* logo_builtin.c - GENERATED by tools/gen_logos.py from src/logo/logos.def; do not edit.  */",
        "",
        '#include "logo/logo.h"',
        "",
        "const FFlogo ffLogoBuiltins[] = {",
    ]
    for f, names, colors, key, title, text in entries:
        lines.append(f"  /* {f} */")
        lines.append("  {")
        lines.append("    { " + ", ".join(f'"{n}"' for n in names) + ", 0 },")
        lines.append(c_string(text) + ",")
        lines.append("    { " + ", ".join(f'"{c}"' for c in colors) + " },")
        lines.append(f'    "{key}", "{title}"')
        lines.append("  },")
    lines.append("};")
    lines.append("")
    lines.append(f"const uint32_t ffLogoBuiltinCount = {len(entries)};")
    (logo_dir / "logo_builtin.c").write_text("\n".join(lines) + "\n")
    print(f"gen_logos: {len(entries)} logos -> src/logo/logo_builtin.c")


main()
